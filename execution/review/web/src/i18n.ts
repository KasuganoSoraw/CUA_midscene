export const messages: Record<WorkbenchLocale, Record<MessageKey, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS,
};

export const localeStorageKey = 'local-workbench-locale';

function validLocale(value: string | null | undefined): WorkbenchLocale | undefined {
  return value === 'zh-CN' || value === 'en-US' ? value : undefined;
}

export function resolveLocale(options: {
  query?: string | null;
  stored?: string | null;
  browserLanguages?: readonly string[];
}): WorkbenchLocale {
  const queryLocale = validLocale(options.query);
  if (queryLocale) return queryLocale;
  const storedLocale = validLocale(options.stored);
  if (storedLocale) return storedLocale;
  return options.browserLanguages?.some((value) => value.toLowerCase().startsWith('zh'))
    ? 'zh-CN'
    : 'en-US';
}

export function translate(locale: WorkbenchLocale, key: MessageKey, params: TranslationParams = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder
  ));
}

function browserLocale(): WorkbenchLocale {
  if (typeof window === 'undefined') return 'zh-CN';
  const query = new URLSearchParams(window.location.search).get('lang');
  let stored: string | null = null;
  try { stored = window.localStorage.getItem(localeStorageKey); } catch { /* storage can be unavailable */ }
  return resolveLocale({ query, stored, browserLanguages: navigator.languages });
}

const localeRef = ref<WorkbenchLocale>(browserLocale());

function syncDocument(locale: WorkbenchLocale): void {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = locale;
  document.title = translate(locale, 'app.title');
}

syncDocument(localeRef.value);

export function useI18n() {
  function t(key: MessageKey, params?: TranslationParams): string {
    return translate(localeRef.value, key, params);
  }

  function setLocale(locale: WorkbenchLocale): void {
    localeRef.value = locale;
    try { window.localStorage.setItem(localeStorageKey, locale); } catch { /* storage can be unavailable */ }
    syncDocument(locale);
  }

  function formatDateTime(value: string | Date): string {
    const date = value instanceof Date ? value : new Date(value);
    return Number.isNaN(date.getTime())
      ? String(value)
      : new Intl.DateTimeFormat(localeRef.value, { dateStyle: 'medium', timeStyle: 'short' }).format(date);
  }

  function formatTime(value: string | Date): string {
    const date = value instanceof Date ? value : new Date(value);
    return Number.isNaN(date.getTime())
      ? String(value)
      : new Intl.DateTimeFormat(localeRef.value, { timeStyle: 'medium' }).format(date);
  }

  return {
    locale: readonly(localeRef),
    t,
    setLocale,
    formatDateTime,
    formatTime,
  };
}
